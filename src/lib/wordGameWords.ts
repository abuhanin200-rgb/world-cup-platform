export const WORD_GAME_WORD_ITEMS = uniqueFiveLetterWords([
  ...SPORTS_RAW.map((word) => ({ word, category: "sports" as const })),
  ...SAUDI_RAW.map((word) => ({ word, category: "saudi" as const })),
  ...GENERAL_RAW.map((word) => ({ word, category: "general" as const })),
]);

export const SPORTS_WORDS = WORD_GAME_WORD_ITEMS.filter(
  (item) => item.category === "sports"
).map((item) => item.word);

export const SAUDI_WORDS = WORD_GAME_WORD_ITEMS.filter(
  (item) => item.category === "saudi"
).map((item) => item.word);

export const COMMON_WORDS = WORD_GAME_WORD_ITEMS.filter(
  (item) => item.category === "general"
).map((item) => item.word);

export const WORD_GAME_WORDS = WORD_GAME_WORD_ITEMS.map((item) => item.word);

export function getWordGameWordCategory(word: string) {
  return (
    WORD_GAME_WORD_ITEMS.find((item) => item.word === normalizeWord(word))
      ?.category ?? "general"
  );
}

export function getWordGameCategoryLabel(category: WordGameWordCategory) {
  if (category === "sports") return "رياضية";
  if (category === "saudi") return "لهجة سعودية";
  return "عامة";
}