export type WordGameWordCategory = "sports" | "saudi" | "general";

export type WordGameWordItem = {
  word: string;
  category: WordGameWordCategory;
};

function normalizeWord(word: string) {
  return word.trim().replace(/\s+/g, "");
}

function isFiveLetters(word: string) {
  return Array.from(normalizeWord(word)).length === 5;
}

function uniqueFiveLetterWords(items: WordGameWordItem[]) {
  const seen = new Set<string>();

  return items
    .map((item) => ({
      ...item,
      word: normalizeWord(item.word),
    }))
    .filter((item) => isFiveLetters(item.word))
    .filter((item) => {
      if (seen.has(item.word)) return false;
      seen.add(item.word);
      return true;
    });
}

